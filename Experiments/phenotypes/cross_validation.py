"""Stratified 10-fold cross-validation of the subgroup lists used as classifiers (E1, RQ1).

Usage:
    python cross_validation.py <view> [number_of_processes]

It requires results/<view>/best_models.csv (generated by select_best_model.ipynb). The folds are grouped by patient
(the same patient never appears in the training and the test data). For each fold and configuration, the candidate
subgroups and the subgroup lists (DSLM algorithm of the subgroups library) are mined with the training data and the best hyperparameters. Then, the test
instances are scored with:
    - without_context: the global lists mined without context attributes.
    - with_context: the global lists mined with context attributes.
    - per_unit: the lists of the unit of the instance (mined only with the training instances of that unit).
Outputs (in results/<view>/cross_validation/):
    - folds.csv: fold of each instance of the mining view.
    - fold_<f>/<configuration>_candidates.txt and fold_<f>/<configuration>_lists.txt.
    - predictions.csv: scores of the test instances.
    - execution_log.txt: standard output of the execution.
"""

import sys
from datetime import datetime
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.model_selection import StratifiedGroupKFold

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import utils
from mine_phenotypes import mine_diverse_topk_subgroup_lists

NUMBER_OF_FOLDS = 10

def cv_path(view : str) -> Path:
    return utils.cross_validation_path(view)

def make_folds(view : str) -> pd.Series:
    df = utils.read_mining_view(view)
    auxiliary = utils.read_auxiliary_data(view)
    folds = pd.Series(-1, index=df.index, name="fold")
    splitter = StratifiedGroupKFold(n_splits=NUMBER_OF_FOLDS, shuffle=True, random_state=utils.RANDOM_SEED)
    for fold, (_, test_index) in enumerate(splitter.split(df, utils.get_target_mask(df), groups=auxiliary["patient_id"])):
        folds.iloc[test_index] = fold
    return folds

def mine_fold(arguments : tuple) -> None:
    view, fold, configuration, b, pos_o, neg_o = arguments
    df = utils.read_mining_view(view)
    folds = pd.read_csv(cv_path(view) / "folds.csv")["fold"]
    train = utils.get_configuration_dataset(df[folds != fold], configuration).reset_index(drop=True)
    path = cv_path(view) / ("fold_" + str(fold))
    path.mkdir(parents=True, exist_ok=True)
    utils.generate_candidate_subgroups(train, utils.TARGET, path / (configuration + "_candidates.txt"))
    mine_diverse_topk_subgroup_lists(train, path / (configuration + "_candidates.txt"), utils.TARGET[0], utils.TARGET[1],
                                     utils.MAXIMUM_NUMBER_OF_SUBGROUP_LISTS, utils.MAXIMUM_NUMBER_OF_SUBGROUPS_PER_SUBGROUP_LIST,
                                     b, pos_o, neg_o, path / (configuration + "_lists.txt"))

def predict(view : str) -> pd.DataFrame:
    df = utils.read_mining_view(view)
    folds = pd.read_csv(cv_path(view) / "folds.csv")["fold"]
    rows = []
    for fold in range(NUMBER_OF_FOLDS):
        path = cv_path(view) / ("fold_" + str(fold))
        train, test = df[folds != fold], df[folds == fold]
        result = pd.DataFrame({"row" : test.index, "fold" : fold, "y" : utils.get_target_mask(test).astype(int), "unit" : test[utils.UNIT_ATTRIBUTE].values})
        for configuration in ["without_context", "with_context"]:
            model = utils.SubgroupListClassifier(utils.read_subgroup_lists(path / (configuration + "_lists.txt")))
            model.fit(train.reset_index(drop=True))
            result["score_" + configuration] = model.predict_proba(test.reset_index(drop=True))
        scores = np.full(len(test), np.nan)
        for unit in utils.UNITS:
            model = utils.SubgroupListClassifier(utils.read_subgroup_lists(path / ("unit_" + unit + "_lists.txt")))
            model.fit(train[train[utils.UNIT_ATTRIBUTE] == unit].reset_index(drop=True))
            in_unit = (test[utils.UNIT_ATTRIBUTE] == unit).to_numpy()
            if in_unit.sum() > 0:
                scores[in_unit] = model.predict_proba(test[in_unit].reset_index(drop=True))
        result["score_per_unit"] = scores
        rows.append(result)
    return pd.concat(rows, ignore_index=True)

if __name__ == '__main__':
    if len(sys.argv) not in (2, 3):
        print("Usage: python cross_validation.py <view> [number_of_processes]")
        exit(1)
    view = sys.argv[1]
    number_of_processes = int(sys.argv[2]) if len(sys.argv) == 3 else 1
    cv_path(view).mkdir(parents=True, exist_ok=True)
    sys.stdout = utils.Tee(cv_path(view) / "execution_log.txt")
    print("Execution: " + str(datetime.now()) + " (" + " ".join(sys.argv) + ")")
    make_folds(view).to_frame().to_csv(cv_path(view) / "folds.csv", index=False)
    best_models = pd.read_csv(utils.best_models_path(view)).set_index("configuration")
    tasks = [(view, fold, configuration,
              best_models.loc[configuration, "beta"], best_models.loc[configuration, "maximum_positive_overlap"], best_models.loc[configuration, "maximum_negative_overlap"])
             for fold in range(NUMBER_OF_FOLDS) for configuration in utils.CONFIGURATIONS]
    print("Number of mining tasks: " + str(len(tasks)))
    start_time = datetime.now()
    with Pool(number_of_processes) as pool:
        for index, _ in enumerate(pool.imap_unordered(mine_fold, tasks)):
            if (index + 1) % 10 == 0:
                print(str(index + 1) + "/" + str(len(tasks)) + " (" + str(datetime.now() - start_time) + ")", flush=True)
    predict(view).to_csv(cv_path(view) / "predictions.csv", index=False)
    print("Total time: " + str(datetime.now() - start_time))
